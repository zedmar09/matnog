/** One sector registration. Validity is always a dated period, never a flag. */
function sector(input: {
  n: number;
  personId: string;
  personLabel: string;
  category: SectorRecord["category"];
  authority: string;
  validFrom: string;
  validTo: string;
  status: SectorRecord["status"];
  source: string;
  evidence: readonly string[];
  credential: string;
  deactivation?: SectorRecord["deactivation"];
}): SectorRecord {
  const { n, deactivation, ...rest } = input;
  return {
    id: `DEMO-SECTOR-${String(n).padStart(3, "0")}`,
    ...rest,
    ...(deactivation ? { deactivation } : {}),
  };
}

